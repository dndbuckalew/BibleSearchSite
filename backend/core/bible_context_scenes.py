# BTA — Scene Context (Free Tier)
# Context 3.2 — Local Scene Context (Part 1)
#
# LAYER ROLE:
# Context = SCENE-SETTING layer
# Context establishes the immediate scriptural setting surrounding
# the requested passage so the reader can understand what is happening,
# who is involved, what circumstance is present, and why the statement
# is being made in that moment.
#
# FREE TIER RULE:
# Context remains Scripture-supporting and non-interpretive.
# It may complete naturally to the point of reader orientation.
# It should not be artificially compressed to a sentence target.
#
# CONTEXT SHOULD:
# - Set the scene
# - Identify who is present
# - Establish what is happening
# - Include the immediate surrounding circumstance
# - Help the reader understand why this statement is being made here
#
# CONTEXT MUST NOT:
# - Interpret doctrine
# - Explain theology
# - Preach
# - Moralize
# - Provide commentary conclusions
# - Introduce external authority
#
# DESIGN PRINCIPLE:
# Context answers:
# “What is happening here, and what surrounding circumstance helps explain why this is being said now?”
#
# Context does not answer:
# “What does this mean doctrinally?”
